export const loadIcons = () => {
  document
    .querySelectorAll(
      Object.keys(iconsRenderer)
        .map(key => `i[icon="${key}"]`)
        .join(', '),
    )
    .forEach(elem => {
      const iconLabel = elem.getAttribute('icon');
      if (!iconLabel) return;

      const icon = iconsRenderer[iconLabel]();
      elem.classList.forEach(classElem => icon.classList.add(classElem));
      elem.replaceWith(icon);
    });

  document
    .querySelectorAll(
      Object.keys(iconsRenderer)
        .map(key => `input[input-icon="${key}"]`)
        .join(', '),
    )
    .forEach(input => {
      const inputCopy = input;
      const inputContainer = document.createElement('div');
      inputContainer.className = 'relative flex items-center';
      input.replaceWith(inputContainer);

      const iconLabel = input.getAttribute('input-icon');
      if (!iconLabel) return;
      const icon = iconsRenderer[iconLabel]();
      'absolute left-4 flex h-5 w-5'
        .split(' ')
        .forEach(classElem => icon.classList.add(classElem));
      inputContainer.appendChild(icon);

      inputCopy.removeAttribute('input-icon');

      inputContainer.appendChild(inputCopy);
    });
};
