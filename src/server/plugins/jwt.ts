import {AssertionError} from 'node:assert';
import {FastifyPluginAsync} from 'fastify';
import {randomBytes} from 'node:crypto';
import fp from 'fastify-plugin';
import SQL from 'sql-template-strings';

let {JWT_SECRET} = process.env;

const plugin: FastifyPluginAsync = async server => {
  if (!JWT_SECRET) {
    const message = 'JWT_SECRET environment variable is not set';

    if (server.dev) {
      JWT_SECRET = randomBytes(32).toString('base64');
      server.log.warn(`${message}, using autogenerated key: ${JWT_SECRET}`);
    } else throw new Error(message);
  }

  await server.register(import('@fastify/jwt'), {
    secret: JWT_SECRET,
    cookie: {
      cookieName: 'refreshToken',
      signed: true,
    },
    sign: {
      expiresIn: '10m',
    },
    async trusted(request, decodedToken) {
      if (decodedToken.type === 'access') {
        const {authorization} = request.headers;
        if (!authorization) return false;

        const token = authorization.split(' ')[1];
        if (!token) return false;

        return (
          (await server.db.get(
            SQL`SELECT user_id FROM tokens WHERE user_id = ${decodedToken.id} AND access = ${token}`,
          )) !== undefined
        );
      }

      if (decodedToken.type === 'refresh') {
        const token = server.unsignCookie(
          request.cookies.refreshToken || '',
        ).value;
        if (!token) return false;

        return (
          (await server.db.get(
            SQL`SELECT user_id FROM tokens WHERE user_id = ${decodedToken.id} AND refresh = ${token}`,
          )) !== undefined
        );
      }

      return false;
    },
  });

  server.decorate('authenticate', async request => {
    await request.jwtVerify();
  });

  server.decorate('authenticateRefresh', async request => {
    try {
      await request.jwtVerify({onlyCookie: true});
    } catch (error) {
      if (!(error instanceof AssertionError) || !request.cookies.refreshToken)
        throw error;

      const cookie = server.unsignCookie(request.cookies.refreshToken);
      if (!cookie.valid)
        throw server.httpErrors.createError(
          401,
          'Untrusted authorization token',
          {
            code: 'FST_JWT_AUTHORIZATION_TOKEN_UNTRUSTED',
          },
        );
    }
  });
};

export default fp(plugin);
