import {FastifyPluginAsync} from 'fastify';
import SQL from 'sql-template-strings';
import {randomBytes} from 'node:crypto';

let {JWT_SECRET} = process.env;

const plugin: FastifyPluginAsync = async server => {
  if (!JWT_SECRET) {
    const message = 'JWT_SECRET environment variable is not set';

    if (server.prod) throw new Error(message);

    JWT_SECRET = randomBytes(32).toString('base64');
    server.log.warn(`${message}, using autogenerated key: ${JWT_SECRET}`);
  }

  server.decorateRequest('connection', null);

  await server.register(import('@fastify/jwt'), {
    secret: JWT_SECRET,
    cookie: {
      cookieName: 'refreshToken',
      signed: false,
    },
    sign: {
      expiresIn: '10m',
    },
    async trusted(request, decodedToken) {
      const query = SQL`SELECT id FROM connections WHERE `;
      let token;

      const {type} = decodedToken;
      if (type === 'access' || type === 'login' || type === 'signup') {
        token = request.headers.authorization?.split(' ')[1];
        query.append(SQL`access_token = ${token}`);
      } else if (type === 'refresh') {
        token = request.cookies.refreshToken;
        query.append(SQL`refresh_token = ${token}`);
      }

      if (!token) return false;

      const connection = await server.db.get(query);
      if (!connection) return false;

      request.connection = connection.id;
      return true;
    },
  });
};

export default plugin;
